def get_prompt_template(mode: str, rules: str = "") -> str:
    """
    根據模式取得對應的 Prompt Template

    Args:
        mode: 專家模式 (itinerary, marketing, costing, legal, general)
        rules: 法規庫內容（用於 legal 和 general 模式）

    Returns:
        str: 對應的系統提示詞
    """
    templates = {
        'itinerary': ITINERARY_PROMPT,
        'marketing': MARKETING_PROMPT,
        'costing': COSTING_PROMPT,
        'legal': LEGAL_PROMPT.format(rules=rules),
        'general': GENERAL_PROMPT.format(rules=rules)
    }

    base_prompt = templates.get(mode, GENERAL_PROMPT.format(rules=rules))
    return f"{base_prompt}\n\n{FUNCTION_CALLING_GUIDE}"


def get_temperature(mode: str) -> float:
    """
    根據模式取得對應的 Temperature 參數

    創意型（0.8）：行程規劃、行銷文案
    嚴謹型（0.1）：成本試算、法規諮詢
    平衡型（0.3）：通用助手

    Args:
        mode: 專家模式

    Returns:
        float: Temperature 值
    """
    temperature_map = {
        'itinerary': 0.8,   # 創意型：需要想像力與彈性
        'marketing': 0.8,   # 創意型：需要吸引力與感染力
        'costing': 0.1,     # 嚴謹型：絕對精準，不容出錯
        'legal': 0.1,       # 嚴謹型：法律問題必須嚴謹
        'general': 0.3      # 平衡型：一般諮詢
    }

    return temperature_map.get(mode, 0.3)


def get_mode_description(mode: str) -> str:
    """取得模式的中文描述"""
    descriptions = {
        'itinerary': '📅 行程規劃專家',
        'marketing': '📝 行銷文案專家',
        'costing': '💰 成本試算專家',
        'legal': '⚖️ 法規諮詢專家',
        'general': '🧭 團控通用助手'
    }
    return descriptions.get(mode, '🧭 團控通用助手')
